export function getPost(slug: string): BlogPost | undefined {
  return POSTS.find((p) => p.slug === slug);
}

/**
 * Reading time, counted from the post itself rather than written by hand, so
 * it stays true when the text is edited.
 */
export function readMinutes(post: BlogPost): number {
  const parts: string[] = [post.title, post.excerpt, ...post.intro];
  for (const section of post.body) {
    parts.push(section.h2);
    for (const block of section.blocks) {
      if (block.k === "ul") parts.push(...block.items);
      else parts.push(block.text);
    }
  }
  const words = parts.join(" ").trim().split(/\s+/).length;
  return Math.max(1, Math.round(words / 180));
}

